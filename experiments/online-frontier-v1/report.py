"""Build tables.md and summary.json from results.jsonl (online-frontier-v1)."""
import json
import math
from pathlib import Path

import numpy as np
from scipy.stats import binomtest

HERE = Path(__file__).resolve().parent
SETS = ["W5k-released", "W5k-fresh", "W10k-fresh", "W100k-fresh", "OR1", "OR2", "OR3", "OR4"]
POLICIES = ["BF", "FS-W", "FS-OR", "ab-WF", "SS", "SS-view", "PD-exp", "PD-exp-T"]
CONTRASTS = [("P1", "SS", "FS-W"), ("P2", "PD-exp", "FS-W"), ("P3", "SS", "FS-OR"), ("P4", "PD-exp", "FS-OR")]
SEED = 20261004


def boot(d, reps=10000):
    rng = np.random.default_rng(SEED)
    d = np.asarray(d, float)
    if len(d) < 2:
        return [float(d.mean())] * 2
    m = d[rng.integers(0, len(d), (reps, len(d)))].mean(1)
    return [float(np.percentile(m, 2.5)), float(np.percentile(m, 97.5))]


def main():
    rows = [json.loads(l) for l in (HERE / "results.jsonl").read_text().splitlines()]
    by = {s: [r for r in rows if r["set"] == s] for s in SETS}
    summ = {"sets": {}, "contrasts": {}, "not_proved": [r["set"] + "/" + r["instance"] for r in rows if not r["opt"]["proved"]]}
    lines = ["# online-frontier-v1 tables", "", "Generated by `report.py` from `results.jsonl`.", ""]

    lines += ["## Bins above the exact optimum (mean per instance)", "",
              "| Set | n | items | OPT − L1 | " + " | ".join(POLICIES) + " |",
              "|---|---|---|---|" + "---|" * len(POLICIES)]
    for s in SETS:
        R = [r for r in by[s] if "opt" in r["opt"]]
        if not R:
            continue
        opt = np.array([r["opt"]["opt"] for r in R], float)
        l1 = np.array([r["L1"] for r in R], float)
        cell, ent = [], {"instances": len(R), "items": R[0]["n"], "opt_minus_L1": float((opt - l1).mean()), "policies": {}}
        for p in POLICIES:
            b = np.array([r["bins"][p] for r in R], float)
            above = b - opt
            ent["policies"][p] = {"bins_above_opt": float(above.mean()),
                                  "excess_over_L1_pct": float(100 * (b.sum() - l1.sum()) / l1.sum()),
                                  "excess_over_opt_pct": float(100 * (b.sum() - opt.sum()) / opt.sum()),
                                  "seconds_mean": float(np.mean([r["seconds"][p] for r in R]))}
            cell.append(f"{above.mean():.2f}")
        best = min(range(len(POLICIES)), key=lambda k: float(cell[k]))
        cell[best] = f"**{cell[best]}**"
        summ["sets"][s] = ent
        lines.append(f"| {s} | {len(R)} | {R[0]['n']:,} | {ent['opt_minus_L1']:.2f} | " + " | ".join(cell) + " |")

    lines += ["", "## Excess over L1 in percent (FunSearch's metric)", "",
              "| Set | " + " | ".join(POLICIES) + " |", "|---|" + "---|" * len(POLICIES)]
    for s in summ["sets"]:
        lines.append(f"| {s} | " + " | ".join(f"{summ['sets'][s]['policies'][p]['excess_over_L1_pct']:.3f}" for p in POLICIES) + " |")

    lines += ["", "## Primary contrasts (bins per instance; negative = first policy uses fewer bins)", "",
              "95% paired bootstrap intervals over instances (10,000 resamples, seed 20261004), unadjusted.", "",
              "| Set | Contrast | Mean | 95% CI | Wins/ties/losses | Sign test p |", "|---|---|---|---|---|---|"]
    excl = 0
    for s in summ["sets"]:
        R = [r for r in by[s] if "opt" in r["opt"]]
        for tag, a, b in CONTRASTS:
            d = np.array([r["bins"][a] - r["bins"][b] for r in R], float)
            w, t, l = int((d < 0).sum()), int((d == 0).sum()), int((d > 0).sum())
            ci = boot(d)
            p = binomtest(w, w + l, 0.5).pvalue if w + l else 1.0
            excl += ci[1] < 0 or ci[0] > 0
            summ["contrasts"][f"{s}/{tag}"] = {"a": a, "b": b, "mean": float(d.mean()), "ci95": ci, "wtl": [w, t, l], "sign_p": p}
            lines.append(f"| {s} | {tag}: {a} − {b} | {d.mean():+.2f} | [{ci[0]:+.2f}, {ci[1]:+.2f}] | {w}/{t}/{l} | {p:.2g} |")
    summ["contrasts_excluding_zero"] = f"{excl}/{len(summ['contrasts'])}"
    # Holm on W5k-fresh sign tests
    fam = sorted([(summ["contrasts"][f"W5k-fresh/{t}"]["sign_p"], t) for t, _, _ in CONTRASTS if f"W5k-fresh/{t}" in summ["contrasts"]])
    holm, m = {}, len(fam)
    running = 0.0
    for k, (p, t) in enumerate(fam):
        running = max(running, min(1.0, (m - k) * p))
        holm[t] = running
    summ["holm_W5k_fresh"] = holm
    lines += ["", f"Intervals excluding 0: {summ['contrasts_excluding_zero']}. Holm-adjusted sign-test p on W5k-fresh: "
              + ", ".join(f"{t} {p:.2g}" for t, p in sorted(holm.items())) + "."]

    lines += ["", "## Mean seconds per instance", "", "| Set | OPT | " + " | ".join(POLICIES) + " |", "|---|---|" + "---|" * len(POLICIES)]
    for s in summ["sets"]:
        R = by[s]
        lines.append(f"| {s} | {np.mean([r['seconds']['OPT'] for r in R]):.1f} | "
                     + " | ".join(f"{summ['sets'][s]['policies'][p]['seconds_mean']:.1f}" for p in POLICIES) + " |")
    if summ["not_proved"]:
        lines += ["", "OPT not proved optimal within the time limit: " + ", ".join(summ["not_proved"])]
    (HERE / "tables.md").write_text("\n".join(lines) + "\n")
    (HERE / "summary.json").write_text(json.dumps(summ, indent=1))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
