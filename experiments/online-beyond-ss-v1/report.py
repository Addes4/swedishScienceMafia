"""Build tables.md and summary.json from results.json (no packing is re-run).

Usage: python experiments/online-beyond-ss-v1/report.py
"""
import json
import math
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
POLICIES = ["FWSS", "FWSS-no-finish", "SS+finish", "SS", "BF", "FS-W", "FS-OR", "abWF", "EoH", "EoH-paper"]
SET_ORDER = ["fs_released_w5k", "fresh_w1k", "fresh_w5k", "fresh_w10k", "fresh_w100k",
             "eoh_1k_c100", "eoh_2k_c100", "eoh_5k_c100", "eoh_10k_c100", "eoh_100k_c100",
             "eoh_1k_c500", "eoh_2k_c500", "eoh_5k_c500", "eoh_10k_c500", "eoh_100k_c500",
             "or1", "or2", "or3", "or4"]
SIGN_TEST_SETS = {"fresh_w1k", "fresh_w5k", "fresh_w10k", "or1", "or2", "or3", "or4"}


def bootstrap_ci(d, reps=10000, seed=20261004):
    d = np.asarray(d, dtype=float)
    if len(d) < 2:
        return (float("nan"), float("nan"))
    rng = np.random.default_rng(seed)
    m = d[rng.integers(0, len(d), size=(reps, len(d)))].mean(axis=1)
    return (float(np.percentile(m, 2.5)), float(np.percentile(m, 97.5)))


def sign_test_p(wins, losses):
    """Two-sided exact sign test (ties dropped)."""
    n = wins + losses
    if n == 0:
        return 1.0
    k = min(wins, losses)
    p = sum(math.comb(n, i) for i in range(k + 1)) / 2 ** n
    return min(1.0, 2 * p)


def main():
    data = json.loads((HERE / "results.json").read_text())
    # Verified corrections to OPT where this study's own solve was unproved (opt_overrides.json,
    # checked by verify_overrides.py). results.json itself is left as produced.
    overrides = json.loads((HERE / "opt_overrides.json").read_text())
    for r in data["instances"]:
        if r["id"] in overrides:
            r["opt"] = overrides[r["id"]]["opt"]
    by_set = {}
    for r in data["instances"]:
        by_set.setdefault(r["set"], []).append(r)
    summary = {"config": data["config"], "sets": {}}
    lines = ["# online-beyond-ss-v1: tables", "",
             "Generated by `report.py` from `results.json`. Excess is over L1 = ⌈Σ sizes / C⌉ (FunSearch's and "
             "EoH's metric): Σ bins / Σ L1 − 1. \"Above OPT\" uses only instances with a known optimum: proved by arc flow "
             "(300 s limit), or, for u250_10 (unproved in 300 s), OR-Library's listed value, which online-frontier-v1 proved optimal. "
             "Four OR-Library listings are not optimal: arc flow proved lower values for u120_08, u120_19 and u250_07, and "
             "u250_12 = 105 comes from a verified 105-bin packing (opt_overrides.json, verify_overrides.py). "
             "FWSS knows the item count T (known horizon); FWSS-no-finish does not.", ""]
    # Table 1: % excess over L1
    hdr = "| Set | n | C | inst | " + " | ".join(POLICIES) + " |"
    lines += ["## 1. Excess over L1 (%)", "", hdr, "|" + "---|" * (4 + len(POLICIES))]
    for s in SET_ORDER:
        rs = by_set.get(s)
        if not rs:
            continue
        L = sum(r["L1"] for r in rs)
        cells = []
        entry = {"n": rs[0]["n"], "C": rs[0]["C"], "instances": len(rs), "excess_pct": {}, "bins_above_L1": {}}
        for p in POLICIES:
            if all(p in r["bins"] for r in rs):
                b = sum(r["bins"][p] for r in rs)
                ex = 100 * (b - L) / L
                entry["excess_pct"][p] = ex
                entry["bins_above_L1"][p] = (b - L) / len(rs)
                cells.append(f"{ex:.3f}")
            else:
                cells.append("–")
        best = min(entry["excess_pct"].values())
        cells = [f"**{c}**" if c != "–" and abs(float(c) - best) < 5e-4 else c for c in cells]
        lines.append(f"| {s} | {rs[0]['n']} | {rs[0]['C']} | {len(rs)} | " + " | ".join(cells) + " |")
        opt_rs = [r for r in rs if r.get("opt") is not None]
        entry["opt_proved"] = len(opt_rs)
        entry["opt_minus_L1_mean"] = float(np.mean([r["opt"] - r["L1"] for r in opt_rs])) if opt_rs else None
        entry["bins_above_OPT"] = {p: float(np.mean([r["bins"][p] - r["opt"] for r in opt_rs]))
                                   for p in POLICIES if opt_rs and all(p in r["bins"] for r in opt_rs)}
        entry["opt_mismatch"] = sum(1 for r in rs if r.get("opt_mismatch"))
        summary["sets"][s] = entry
    # Table 2: bins above OPT
    lines += ["", "## 2. Mean bins above the proved optimum per instance", "",
              "| Set | OPT known | OPT − L1 | " + " | ".join(POLICIES) + " |", "|" + "---|" * (3 + len(POLICIES))]
    for s in SET_ORDER:
        e = summary["sets"].get(s)
        if not e or not e["opt_proved"]:
            continue
        cells = [f"{e['bins_above_OPT'][p]:.2f}" if p in e["bins_above_OPT"] else "–" for p in POLICIES]
        lines.append(f"| {s} | {e['opt_proved']}/{e['instances']} | {e['opt_minus_L1_mean']:.2f} | " + " | ".join(cells) + " |")
    # Table 3: paired contrasts
    lines += ["", "## 3. Paired contrasts (bins per instance; negative = FWSS uses fewer bins)", "",
              "| Set | contrast | mean | 95% bootstrap CI | W/T/L | sign-test p |", "|---|---|---|---|---|---|"]
    for s in SET_ORDER:
        rs = by_set.get(s)
        if not rs:
            continue
        ref = "FS-OR" if s.startswith("or") else "FS-W"
        summary["sets"][s]["contrasts"] = {}
        for other in (ref, "SS", "FWSS-no-finish"):
            d = np.array([r["bins"]["FWSS"] - r["bins"][other] for r in rs])
            w, t, l = int((d < 0).sum()), int((d == 0).sum()), int((d > 0).sum())
            lo, hi = bootstrap_ci(d)
            p = sign_test_p(w, l) if s in SIGN_TEST_SETS else None
            summary["sets"][s]["contrasts"][f"FWSS-{other}"] = {"mean": float(d.mean()), "ci": [lo, hi], "wtl": [w, t, l], "sign_p": p}
            ptxt = f"{p:.2g}" if p is not None else "–"
            lines.append(f"| {s} | FWSS − {other} | {d.mean():+.2f} | [{lo:+.2f}, {hi:+.2f}] | {w}/{t}/{l} | {ptxt} |")
    # Positive control: EoH's own published table (eoh_data/results.txt, commit 5d3319e) on EoH's own data
    eoh_pub = {"BF": [4.46, 4.18, 4.01, 0.99, 0.45, 0.50], "EoH-paper": [2.63, 0.67, 0.55, 0.99, 0.45, 0.35],
               "EoH": [2.53, 0.75, 0.52, 0.74, 0.45, 0.37]}
    cols = ["eoh_1k_c100", "eoh_5k_c100", "eoh_10k_c100", "eoh_1k_c500", "eoh_5k_c500", "eoh_10k_c500"]
    lines += ["", "## 4. Positive control: EoH's published table, reproduced on EoH's data", "",
              "EoH's `results.txt` (2 decimals) against our recomputation, with the same instances and evaluator semantics.", "",
              "| Policy | " + " | ".join(cols) + " |", "|---|" + "---|" * len(cols)]
    summary["eoh_positive_control"] = {}
    for p, pub in eoh_pub.items():
        ours = [summary["sets"][c]["excess_pct"].get(p) if c in summary["sets"] else None for c in cols]
        ok = all(o is not None and round(o, 2) == v for o, v in zip(ours, pub))
        summary["eoh_positive_control"][p] = {"ours": ours, "published": pub, "match_2dp": ok}
        lines.append(f"| {p} | " + " | ".join(f"{o:.2f} (pub {v:.2f})" if o is not None else "–" for o, v in zip(ours, pub)) + " |")
    (HERE / "tables.md").write_text("\n".join(lines) + "\n")
    (HERE / "summary.json").write_text(json.dumps(summary, indent=1))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
