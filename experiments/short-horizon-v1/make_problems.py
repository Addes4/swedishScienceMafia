@lru_cache(maxsize=4096)
def items_for(seed: int, n: int) -> tuple:
    digest = hashlib.sha256(f"{{_SALT}}:{{seed}}".encode()).digest()
    rng = random.Random(int.from_bytes(digest[:8], "big"))
    return tuple(min(CAPACITY, max(1, int(rng.weibullvariate(45.0, 3.0)))) for _ in range(n))


def l2_bound(items, capacity=CAPACITY) -> int:
    """Martello-Toth (1990) L2 lower bound for integer item sizes."""
    counts = [0] * (capacity + 1)
    for x in items:
        counts[x] += 1
    best = math.ceil(sum(items) / capacity)
    for k in range(0, capacity // 2 + 1):
        n1 = sum(counts[capacity - k + 1:])
        j2 = range(capacity // 2 + 1, capacity - k + 1)
        n2 = sum(counts[s] for s in j2)
        s2 = sum(s * counts[s] for s in j2)
        s3 = sum(s * counts[s] for s in range(max(k, 1), capacity // 2 + 1))
        best = max(best, n1 + n2 + max(0, math.ceil((s3 - (n2 * capacity - s2)) / capacity)))
    return best


@lru_cache(maxsize=8)
def _suite(name):
    return tuple(tuple(s) for s in json.loads((Path(__file__).parent / name).read_text())["streams"])


def streams(instance):
    if "suite" in instance:
        return [list(s) for s in _suite(instance["suite"])]
    return [list(items_for(seed, n)) for seed, n in instance["streams"]]


def best_fit_bins(items, capacity=CAPACITY):
    gaps = []
    for x in items:
        fits = [g for g in gaps if g >= x]
        if fits:
            g = min(fits)
            gaps[gaps.index(g)] = g - x
        else:
            gaps.append(capacity - x)
    return len(gaps)


def online(instance):
    ss = streams(instance)
    return {{"capacity": CAPACITY, "streams": [len(s) for s in ss]}}, [x for s in ss for x in s]


def label(instance):
    ss = streams(instance)
    lens = sorted(set(len(s) for s in ss))
    if "suite" in instance:
        return f"{{instance['name']}} ({{len(ss)}} short streams of {{lens[0]}}-{{lens[-1]}} items)"
    total = sum(l2_bound(s) for s in ss)
    shape = f"{{len(ss)}} streams of {{lens[0]}} items" if len(ss) > 1 else f"{{lens[0]}} items"
    return f"{{instance['name']}} ({{shape}}, lower bound {{total}} bins)"


