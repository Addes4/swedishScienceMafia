"""Build tables.md and summary.json from the saved results (no solving, seconds to run).

    python analyze.py
"""
import json
import os
import tarfile

import numpy as np


def ensure_results():
    """Unpack results.tar.gz (the committed raw per-instance results) if results/ is missing."""
    if not os.path.isdir("results") and os.path.exists("results.tar.gz"):
        with tarfile.open("results.tar.gz") as t:
            t.extractall(".", filter="data")

SETS = ["mctsahd_test50", "mctsahd_test100", "mctsahd_test200", "fresh50", "fresh100", "fresh200"]
N_OF = {s: int("".join(c for c in s.split("_")[-1] if c.isdigit())) for s in SETS}

# MCTS-AHD (arXiv 2501.08603) Table 1, step-by-step construction, TSP; gaps in % (mean of 3 runs).
PUBLISHED = {
    "Nearest neighbour ('Greedy Construct')": (22.62, 24.94, 26.29),
    "POMO (neural, trained; not an AHD method)": (0.39, 3.01, 20.45),
    "FunSearch (GPT-3.5-turbo)": (17.75, 18.95, 19.61),
    "EoH (GPT-3.5-turbo)": (12.59, 14.96, 17.63),
    "MCTS-AHD (GPT-3.5-turbo)": (11.82, 14.08, 16.51),
    "FunSearch (GPT-4o-mini)": (12.00, 13.93, 15.54),
    "EoH (GPT-4o-mini)": (12.67, 14.49, 16.68),
    "MCTS-AHD (GPT-4o-mini)": (9.69, 11.79, 13.71),
}
PUBLISHED_OPT = (5.675, 7.768, 10.659)

LLM_RERUN = ["tide_appendix", "mctsahd_gpt4omini_best", "hifo_best", "reevo_best", "ael_best", "refineevo_released", "clade_released"]
INTERFACE = ["nearest_neighbour", "fi_emit", "greedy_ls_emit", "lkh_emit", "fi_replan", "nn_rollout"]
CLASSICAL_SHOW = [
    "nearest_neighbour", "farthest_insertion", "random_insertion", "savings", "greedy_edge",
    "nearest_neighbour+2opt", "farthest_insertion+2opt", "greedy_edge+2opt",
    "farthest_insertion+2opt+oropt", "savings+2opt+oropt", "greedy_edge+2opt+oropt",
]


def tag_file(s):
    return s.replace("mctsahd_", "")


def load_lkh(s):
    return np.load(f"results/lkh_{tag_file(s)}.npy")


def load_interface(h, s):
    """Concatenate chunks (eval_interface.py --start) in order."""
    tag = tag_file(s)
    parts = []
    for f in sorted(os.listdir("results")):
        if f.startswith(f"interface_{h}_{tag}") and f.endswith(".json"):
            rest = f[len(f"interface_{h}_{tag}"):-5]
            if rest == "" or (rest.startswith("_") and rest[1:].isdigit()):
                d = json.load(open(os.path.join("results", f)))
                parts.append((d.get("start", 0), d))
    if not parts:
        return None
    parts.sort(key=lambda p: p[0])
    L, W, pos = [], [], 0
    for start, d in parts:
        assert start == pos, f"gap in chunks for {h} {s}: expected {pos}, got {start}"
        L += d["lengths"]
        W += d["wall_seconds"]
        pos += len(d["lengths"])
    return np.array(L), np.array(W)


def load_classical(s):
    p = f"results/classical_{tag_file(s)}.json"
    if not os.path.exists(p):
        return {}
    d = json.load(open(p))["methods"]
    return {k: (np.array(v["lengths"]), v["seconds"] / len(v["lengths"])) for k, v in d.items()}


def gap(L, opt):
    return 100 * (L.mean() / opt[: len(L)].mean() - 1)


def boot_ci(diff, reps=10000, seed=0):
    rng = np.random.default_rng(seed)
    idx = rng.integers(0, len(diff), size=(reps, len(diff)))
    m = diff[idx].mean(1)
    return float(np.percentile(m, 2.5)), float(np.percentile(m, 97.5))


def paired(a, b):
    k = min(len(a), len(b))
    d = a[:k] - b[:k]
    lo, hi = boot_ci(d)
    return {
        "n_instances": k,
        "mean_diff": float(d.mean()),
        "ci95": [lo, hi],
        "wins": int((d < -1e-9).sum()),
        "ties": int((np.abs(d) <= 1e-9).sum()),
        "losses": int((d > 1e-9).sum()),
    }


def main():
    ensure_results()
    summary = {"sets": {}, "published_mctsahd_table1": PUBLISHED, "positive_control": {}}
    lines = ["# tsp-construct-v1 tables", "", "Generated by `analyze.py` from `results/`. Gap = mean "
             "length / mean LKH length − 1 (ratio of means, as in MCTS-AHD's Table 1).", ""]
    # positive control
    lines += ["## Positive control: LKH optimum means", "", "| Set | ours | MCTS-AHD published | diff |",
              "|---|---|---|---|"]
    for s, pub in zip(SETS[:3], PUBLISHED_OPT):
        if os.path.exists(f"results/lkh_{tag_file(s)}.npy"):
            m = float(load_lkh(s).mean())
            summary["positive_control"][s] = {"ours": m, "published": pub, "pass": abs(m - pub) < 0.002}
            lines.append(f"| {s} | {m:.4f} | {pub:.3f} | {m - pub:+.4f} |")
    lines.append("")
    for s in SETS:
        if not os.path.exists(f"results/lkh_{tag_file(s)}.npy"):
            continue
        opt = load_lkh(s)
        n = N_OF[s]
        rows = {}
        for h in LLM_RERUN + INTERFACE:
            r = load_interface(h, s)
            if r is not None:
                rows[h] = {"lengths": r[0], "sec": float(np.median(r[1])), "kind": "LLM re-run" if h in LLM_RERUN else "interface"}
        for k, (L, sec) in load_classical(s).items():
            if k in CLASSICAL_SHOW:
                rows["numba:" + k] = {"lengths": L, "sec": sec, "kind": "classical (numba, outside interface)"}
        ss = {"lkh_mean": float(opt.mean()), "n_instances": int(len(opt)), "methods": {}, "paired": {}}
        lines += [f"## {s} (n = {n}, {len(opt)} instances, LKH mean {opt.mean():.4f})", "",
                  "| Method | kind | instances | mean length | gap % | mean per-instance gap % | sec/instance |",
                  "|---|---|---|---|---|---|---|"]
        for h, r in sorted(rows.items(), key=lambda kv: gap(kv[1]["lengths"], opt)):
            L = r["lengths"]
            g = gap(L, opt)
            pg = float(100 * (L / opt[: len(L)] - 1).mean())
            ss["methods"][h] = {"kind": r["kind"], "instances": int(len(L)), "mean_length": float(L.mean()),
                                "gap_pct": float(g), "mean_instance_gap_pct": pg, "sec_per_instance": r["sec"]}
            lines.append(f"| {h} | {r['kind']} | {len(L)} | {L.mean():.4f} | {g:.2f} | {pg:.2f} | {r['sec']:.4f} |")
        if s.startswith("mctsahd"):
            i = [50, 100, 200].index(n)
            for name, gp in PUBLISHED.items():
                lines.append(f"| {name} | published (MCTS-AHD Table 1) | 1000 | — | {gp[i]:.2f} | — | — |")
        lines.append("")
        # paired comparisons
        comps = [(c, h) for h in LLM_RERUN for c in ("nearest_neighbour", "fi_emit", "greedy_ls_emit")] + \
                [("fi_emit", "numba:farthest_insertion"), ("greedy_ls_emit", "numba:greedy_edge+2opt+oropt"),
                 ("fi_replan", "fi_emit"), ("nn_rollout", "mctsahd_gpt4omini_best"), ("hifo_best", "mctsahd_gpt4omini_best")]
        plines = []
        for a, b in comps:
            if a in rows and b in rows:
                p = paired(rows[a]["lengths"], rows[b]["lengths"])
                ss["paired"][f"{a} - {b}"] = p
                plines.append(f"| {a} − {b} | {p['n_instances']} | {p['mean_diff']:+.4f} | "
                              f"[{p['ci95'][0]:+.4f}, {p['ci95'][1]:+.4f}] | {p['wins']}/{p['ties']}/{p['losses']} |")
        if plines:
            lines += ["Paired per-instance length differences (negative = first is shorter); 95% bootstrap CI; "
                      "wins/ties/losses for the first.", "",
                      "| Comparison | instances | mean diff | 95% CI | W/T/L |", "|---|---|---|---|---|"] + plines + [""]
        summary["sets"][s] = ss
    open("tables.md", "w").write("\n".join(lines) + "\n")
    json.dump(summary, open("summary.json", "w"), indent=1)
    print("\n".join(lines))


if __name__ == "__main__":
    main()


# ---- pre-registered hypothesis checks (PROTOCOL.md) ----
# Best published pure select_next_node gaps (literature.md §1a), used by H1.
H1_BAR = {50: ("TIDE", 4.76), 100: ("SimpleEvol", 6.47), 200: ("HiFo-Prompt", 8.877)}
H1_SECONDARY = {100: [("TIDE", 7.15), ("RefineEvo-Opus (inferred)", 3.3)], 200: [("RefineEvo-Opus (inferred)", 4.7)]}
# MCTS-AHD-lineage rows used by H3 (literature.md §1a), gaps in % at n = 50, 100, 200.
H3_ROWS = {
    "MCTS-AHD T1 FunSearch GPT-3.5": (17.75, 18.95, 19.61), "MCTS-AHD T1 EoH GPT-3.5": (12.59, 14.96, 17.63),
    "MCTS-AHD T1 MCTS-AHD GPT-3.5": (11.82, 14.08, 16.51), "MCTS-AHD T1 FunSearch GPT-4o-mini": (12.00, 13.93, 15.54),
    "MCTS-AHD T1 EoH GPT-4o-mini": (12.67, 14.49, 16.68), "MCTS-AHD T1 MCTS-AHD GPT-4o-mini": (9.69, 11.79, 13.71),
    "CALM T2": (10.04, 11.58, 13.41), "Clade-AHD T-I": (10.39, 9.22, 11.30), "MoH T1": (9.893, 11.444, 13.307),
    "PathWise T1": (8.41, 11.85, 12.14),
}


def hypotheses():
    S = json.load(open("summary.json"))
    out = {}
    lines = ["## Pre-registered hypotheses", ""]
    for n in (50, 100, 200):
        s = S["sets"].get(f"mctsahd_test{n}")
        if not s:
            continue
        M, P = s["methods"], s["paired"]
        i = (50, 100, 200).index(n)
        res = {}
        if "greedy_ls_emit" in M:
            g = M["greedy_ls_emit"]["gap_pct"]
            name, bar = H1_BAR[n]
            res["H1"] = {"greedy_ls_emit_gap": g, "bar": bar, "bar_source": name, "holds": g < bar,
                         "secondary": [(nm, b, g < b) for nm, b in H1_SECONDARY.get(n, [])]}
        h2 = {}
        for h in LLM_RERUN:  # tide_appendix is exploratory (not in PROTOCOL.md); labelled below
            if h not in M:
                continue
            ok = []
            for c in ("nearest_neighbour", "fi_emit", "greedy_ls_emit"):
                p = P.get(f"{c} - {h}")
                if p and c in M and p["ci95"][1] < 0 and M[c]["sec_per_instance"] <= M[h]["sec_per_instance"]:
                    ok.append(c)
            h2[h] = {"dominated_by": ok, "holds": bool(ok)}
        res["H2"] = h2
        if "fi_emit" in M:
            g = M["fi_emit"]["gap_pct"]
            rows = {k: (v[i], g < v[i]) for k, v in H3_ROWS.items()}
            pr = {h: P.get(f"fi_emit - {h}", {}).get("ci95") for h in ("mctsahd_gpt4omini_best", "reevo_best", "ael_best")}
            pending = [h for h, ci in pr.items() if ci is None]
            res["H3"] = {"fi_emit_gap": g, "published_rows": rows, "paired_ci": pr, "pending": pending,
                         "holds": None if pending else (all(b for _, b in rows.values()) and all(ci[1] < 0 for ci in pr.values()))}
        out[n] = res
        lines.append(f"### n = {n}")
        if "H1" in res:
            r = res["H1"]
            lines.append(f"- H1: greedy_ls_emit gap {r['greedy_ls_emit_gap']:.2f}% vs best published {r['bar']}% ({r['bar_source']}): "
                         f"**{'holds' if r['holds'] else 'fails'}**. Secondary: " +
                         (", ".join(f"{nm} {b}% → {'below' if ok else 'not below'}" for nm, b, ok in r["secondary"]) or "none"))
        for h, r in h2.items():
            tag = " (exploratory, not pre-registered)" if h == "tide_appendix" else ""
            lines.append(f"- H2 vs {h}{tag}: {'dominated by ' + ', '.join(r['dominated_by']) if r['holds'] else '**not dominated**'}")
        if "H3" in res:
            r = res["H3"]
            lines.append(f"- H3: fi_emit gap {r['fi_emit_gap']:.2f}%; below all {len(r['published_rows'])} lineage rows: "
                         f"{all(b for _, b in r['published_rows'].values())}; paired CIs below 0: "
                         f"{ {h: (None if ci is None else ci[1] < 0) for h, ci in r['paired_ci'].items()} } → **{'pending' if r['holds'] is None else ('holds' if r['holds'] else 'fails')}**")
        lines.append("")
    # H4: signs on fresh sets
    h4 = {}
    for n in (50, 100, 200):
        a, b = S["sets"].get(f"mctsahd_test{n}"), S["sets"].get(f"fresh{n}")
        if not (a and b):
            continue
        for k, p in a["paired"].items():
            q = b["paired"].get(k)
            # H4 covers the H2/H3 comparisons against re-run LLM heuristics; implementation-identity checks
            # (vs the numba versions) are excluded.
            if q and "numba:" not in k and (k.startswith("fi_emit - ") or k.startswith("greedy_ls_emit - ")
                                            or k.startswith("nearest_neighbour - ")):
                h4[f"n{n}: {k}"] = {"test_sign": np.sign(p["mean_diff"]), "fresh_sign": np.sign(q["mean_diff"]),
                                    "same": bool(np.sign(p["mean_diff"]) == np.sign(q["mean_diff"]))}
    if h4:
        bad = [k for k, v in h4.items() if not v["same"]]
        lines += ["### H4 (fresh sets)", f"- {len(h4) - len(bad)} of {len(h4)} paired comparisons keep their sign on fresh instances."
                  + (f" Changed: {bad}" if bad else ""), ""]
    out["H4"] = {k: {kk: (float(vv) if not isinstance(vv, bool) else vv) for kk, vv in v.items()} for k, v in h4.items()}
    S["hypotheses"] = out
    json.dump(S, open("summary.json", "w"), indent=1, default=float)
    with open("tables.md", "a") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    hypotheses()
