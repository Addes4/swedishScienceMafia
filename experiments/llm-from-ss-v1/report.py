"""Build tables.md and summary.json for llm-from-ss-v1 from audit.json and the run folders.

    python experiments/llm-from-ss-v1/report.py
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ORDER = ["best_fit", "funsearch_weibull", "sum_of_squares", "fwss"]


def runs():
    out = {}
    for d in sorted((HERE / "runs").glob("s*")):
        if not d.is_dir():
            continue
        s = json.loads((d / "summary.json").read_text()) if (d / "summary.json").exists() else {}
        loop = json.loads((d / "loop.json").read_text()) if (d / "loop.json").exists() else {}
        usage = [json.loads(l) for l in (d / "usage.jsonl").read_text().splitlines()] if (d / "usage.jsonl").exists() else []
        calls = [u for u in usage if u.get("event") == "call"]
        out[d.name] = {
            "status": s.get("status"), "arm_result": s.get("arm_result"), "calls": s.get("calls"),
            "failed_calls": s.get("failed_calls"), "evals": s.get("evals"), "valid_evals": s.get("valid_evals"),
            "improvements": s.get("improvements"), "initial_public": s.get("initial_public"),
            "initial_hidden": s.get("initial_hidden"), "final_public": s.get("final_public"),
            "final_hidden": s.get("final_hidden"), "spent_usd_summary": s.get("spent_usd"),
            "spent_usd_recomputed": round(sum(u.get("cost_usd") or 0 for u in calls), 6),
            "llm_seconds": round(sum(u.get("seconds") or 0 for u in calls), 1),
            "wall_s": s.get("wall_s"), "timings": loop.get("timings"),
            "errors": sorted({str(u.get("error"))[:80] for u in calls if u.get("error")}),
        }
    return out


def f(x, d=4):
    return "—" if x is None else (f"{x:.{d}f}" if isinstance(x, float) else str(x))


def main():
    audit = json.loads((HERE / "audit.json").read_text())
    S = audit["summary"]
    R = runs()
    names = ORDER + sorted(k for k in S if k.startswith("run_"))
    L = ["# llm-from-ss-v1 tables", "", "Generated by `report.py` from `audit.json` and `runs/*/`.", "",
         f"## Fresh audit: {audit['seeds'][1] - audit['seeds'][0] + 1} unseen 5,000-item instances "
         f"(seeds {audit['seeds'][0]}–{audit['seeds'][1]})", "",
         "Bins are per instance; contrasts are mean bins minus the reference, 95% paired bootstrap interval "
         f"(seed {audit['bootstrap']['seed']}, {audit['bootstrap']['draws']} resamples), wins/ties/losses.", "",
         "| Program | Valid | Bins above OPT | Excess over L1 % | vs Sum-of-Squares | vs FunSearch | vs FWSS | Agreement with SS | Agreement with FunSearch | Uses horizon |",
         "|---|---|---|---|---|---|---|---|---|---|"]

    def c(e, k):
        x = e.get(k)
        if not x:
            return "—"
        return f"{x['mean']:+.2f} [{x['ci95'][0]:+.2f}, {x['ci95'][1]:+.2f}] {x['wins']}/{x['ties']}/{x['losses']}"

    for n in names:
        e = S.get(n)
        if e is None:
            continue
        L.append(f"| {n} | {e['valid']}/{e['instances']} | {f(e.get('bins_above_opt'), 2)} | {f(e.get('excess_over_L1_pct'), 3)} | "
                 f"{c(e, 'vs_sum_of_squares')} | {c(e, 'vs_funsearch_weibull')} | {c(e, 'vs_fwss')} | "
                 f"{f(e.get('decision_agreement_sum_of_squares'), 3)} | {f(e.get('decision_agreement_funsearch_weibull'), 3)} | "
                 f"{e['horizon']['uses_horizon']} {e['horizon']['differing_decisions_in_prefix']} |")
    L += ["", "## Runs", "",
          "| Run | Result | Calls (failed) | Evals (valid) | Improvements | Public: initial → final | Hidden: initial → final | Spend (recomputed) | LLM seconds | Wall s |",
          "|---|---|---|---|---|---|---|---|---|---|"]
    for k, r in R.items():
        L.append(f"| {k} | {r['status']}/{r['arm_result']} | {r['calls']} ({r['failed_calls']}) | {r['evals']} ({r['valid_evals']}) | "
                 f"{r['improvements']} | {f(r['initial_public'])} → {f(r['final_public'])} | {f(r['initial_hidden'])} → {f(r['final_hidden'])} | "
                 f"${f(r['spent_usd_recomputed'])} | {r['llm_seconds']} | {r['wall_s']} |")
    total = round(sum(r["spent_usd_recomputed"] for r in R.values()), 4)
    L += ["", f"Total spend recomputed from usage.jsonl: ${total} (cap $2.50)."]
    opt = audit["optimum"]
    L += ["", f"Optimum proved on {sum(o['proved'] for o in opt.values())}/{len(opt)} audit instances."]
    (HERE / "tables.md").write_text("\n".join(L) + "\n")
    out = {"experiment": "llm-from-ss-v1", "audit_seeds": audit["seeds"], "programs": S, "runs": R, "total_spend_usd": total,
           "beats_sum_of_squares": {k: S[k].get("beats_sum_of_squares") for k in S if k.startswith("run_")}}
    (HERE / "summary.json").write_text(json.dumps(out, indent=1))
    print("\n".join(L))


if __name__ == "__main__":
    main()
